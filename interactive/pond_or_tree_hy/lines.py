def armenian(clip, script):
    """The English SCRIPT of one clip with every spoken line replaced by its Armenian text."""
    out = []
    for e in script:
        if type(e).__name__ == "Say":
            e = replace(e, text=LINES[ALIASES.get((clip, e.id), e.id)])
        out.append(e)
    return out
